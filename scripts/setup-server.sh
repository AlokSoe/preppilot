#!/usr/bin/env bash
# One-time setup of PrepPilot on a fresh Ubuntu server (e.g. Oracle Cloud Always Free).
#
#   curl -fsSL https://raw.githubusercontent.com/AlokSoe/preppilot/main/scripts/setup-server.sh -o setup.sh
#   bash setup.sh your-name.duckdns.org
#
# What it does: opens ports 80/443, installs Docker, clones PrepPilot, clones the
# PRIVATE note repos using read-only deploy keys (one per repo, so the server can
# read only those two repos), writes .env with fresh secrets and NO API key
# (users add their own in Settings), then starts Caddy + api + runner.
# Safe to run again: every step skips what is already done.

set -euo pipefail

DOMAIN="${1:-}"
if [[ -z "$DOMAIN" ]]; then
  echo "Usage: bash setup.sh <your-domain>   (e.g. preppilot-kumar.duckdns.org)" >&2
  exit 1
fi
NOTE_REPOS=("AlokSoe/machine-coding-js" "AlokSoe/javascript-engineering-handbook")
APP_REPO="https://github.com/AlokSoe/preppilot.git"

step() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

step "1/6 Firewall: allow HTTP and HTTPS"
# Oracle's Ubuntu images reject new connections except SSH, even with the
# cloud Security List open. Insert ACCEPT rules once.
for port in 80 443; do
  if ! sudo iptables -C INPUT -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null; then
    sudo iptables -I INPUT 6 -p tcp --dport "$port" -m state --state NEW -j ACCEPT
  fi
done
sudo netfilter-persistent save >/dev/null 2>&1 || echo "(netfilter-persistent not found: rules last until reboot)"

step "2/6 Docker"
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sudo sh
fi
sudo usermod -aG docker "$USER"

step "3/6 PrepPilot code"
cd "$HOME"
[[ -d preppilot ]] || git clone "$APP_REPO" preppilot
cd preppilot
git pull --ff-only
mkdir -p notes

step "4/6 Read-only deploy keys for the private note repos"
mkdir -p "$HOME/.ssh" && chmod 700 "$HOME/.ssh"
touch "$HOME/.ssh/config" && chmod 600 "$HOME/.ssh/config"
ssh-keyscan -t ed25519 github.com >>"$HOME/.ssh/known_hosts" 2>/dev/null
need_keys=()
for repo in "${NOTE_REPOS[@]}"; do
  name="${repo#*/}"
  key="$HOME/.ssh/deploy_$name"
  [[ -f "$key" ]] || ssh-keygen -q -t ed25519 -N "" -f "$key" -C "preppilot-server:$name"
  # GitHub needs a different deploy key per repo, so each repo gets a host alias.
  if ! grep -q "^Host github-$name\$" "$HOME/.ssh/config"; then
    printf 'Host github-%s\n  HostName github.com\n  User git\n  IdentityFile %s\n  IdentitiesOnly yes\n\n' "$name" "$key" >>"$HOME/.ssh/config"
  fi
  [[ -d "notes/$name" ]] || need_keys+=("$repo")
done

if ((${#need_keys[@]} > 0)); then
  echo
  echo "Add each key below on GitHub as a deploy key (leave 'Allow write access' UNCHECKED):"
  for repo in "${need_keys[@]}"; do
    name="${repo#*/}"
    echo
    echo "  $repo  →  https://github.com/$repo/settings/keys/new   (title: preppilot-server)"
    echo "  $(cat "$HOME/.ssh/deploy_$name.pub")"
  done
  echo
  read -r -p "Press Enter once both keys are added... " _
  for repo in "${need_keys[@]}"; do
    name="${repo#*/}"
    git clone --depth 1 "git@github-$name:$repo.git" "notes/$name"
  done
fi

step "5/6 Configuration (.env)"
if [[ -f .env ]]; then
  echo ".env already exists: keeping it"
else
  umask 077
  cat >.env <<EOF
# Generated by setup-server.sh. Keep this file private.
DOMAIN=$DOMAIN

# No server API key: the demo tier is off and every user adds their own key in Settings.
ANTHROPIC_API_KEY=
DEMO_ENABLED=false

# Encrypts users' API keys at rest. If lost, users simply re-enter their keys.
KEY_ENCRYPTION_SECRET=$(openssl rand -hex 32)
RUNNER_TOKEN=$(openssl rand -hex 24)
EOF
  umask 022
  echo "Wrote .env (no API key, demo tier off, fresh secrets)"
fi

step "6/6 Start Caddy (HTTPS) + api + runner"
sudo docker compose up -d --build
echo
echo "Done. In a minute or two, open: https://$DOMAIN"
echo "Logs:   cd ~/preppilot && sudo docker compose logs -f api"
echo "Update: cd ~/preppilot && git pull && sudo docker compose up -d --build"
